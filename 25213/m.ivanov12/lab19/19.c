#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <dirent.h>

/*
 * Функция match проверяет, соответствует ли имя файла заданному шаблону.
 *
 * Параметр pattern — указатель на текущую позицию в шаблоне.
 * Параметр filename — указатель на текущую позицию в имени файла.
 *
 * Возвращает:
 *     1 — если имя файла соответствует шаблону;
 *     0 — если не соответствует.
 *
 * Правила шаблона:
 *
 *     '*' — соответствует любой последовательности символов,
 *           в том числе пустой последовательности.
 *
 *     '?' — соответствует ровно одному любому символу.
 *
 *     Любой другой символ — должен совпадать с таким же символом
 *     в имени файла.
 */
int match(const char *pattern, const char *filename)
{
    /*
     * Если текущий символ шаблона — '\0',
     * значит мы дошли до конца шаблона.
     *
     * В этом случае имя файла тоже должно закончиться.
     *
     * Например:
     *
     * pattern:  "test"
     * filename: "test"
     *
     * Оба указателя находятся на '\0',
     * поэтому строки полностью совпали.
     */
    if (*pattern == '\0')
    {
        return *filename == '\0';
    }

    /*
     * Если текущий символ шаблона — '*',
     * то звёздочка может соответствовать:
     *
     * 1. Пустой последовательности символов.
     *
     * 2. Одному символу.
     *
     * 3. Двум символам.
     *
     * 4. N символам.
     *
     * Поэтому рассматриваем два варианта.
     */
    if (*pattern == '*')
    {
        /*
         * Вариант №1:
         *
         * '*' соответствует пустой последовательности.
         *
         * Мы просто переходим к следующему символу шаблона,
         * но имя файла пока не изменяем.
         *
         * Например:
         *
         * pattern:  "*abc"
         * filename: "abc"
         *
         * '*' может ничего не соответствовать.
         */
        if (match(pattern + 1, filename))
        {
            return 1;
        }

        /*
         * Вариант №2:
         *
         * '*' соответствует текущему символу имени файла.
         *
         * После этого мы оставляем '*' на месте и пытаемся
         * сопоставить его со следующим символом имени файла.
         *
         * Например:
         *
         * pattern:  "*abc"
         * filename: "123abc"
         *
         * Сначала '*' забирает '1',
         * потом '2',
         * потом '3'.
         *
         * После этого шаблон "*abc" сравнивается с "abc".
         */
        if (*filename != '\0')
        {
            return match(pattern, filename + 1);
        }

        /*
         * Если имя файла уже закончилось,
         * а '*' не позволила получить совпадение,
         * значит соответствия нет.
         */
        return 0;
    }

    /*
     * Если текущий символ шаблона — '?',
     * он должен соответствовать ровно одному символу.
     *
     * Поэтому имя файла не должно закончиться.
     *
     * Если символ существует, переходим одновременно
     * к следующему символу шаблона и следующему символу имени.
     */
    if (*pattern == '?')
    {
        /*
         * Если имя файла уже закончилось,
         * '?' не может соответствовать пустой строке.
         */
        if (*filename == '\0')
        {
            return 0;
        }

        /*
         * '?' соответствует одному символу,
         * поэтому двигаем оба указателя на один символ вперёд.
         */
        return match(pattern + 1, filename + 1);
    }

    /*
     * Если текущий символ шаблона обычный,
     * то он должен быть точно таким же,
     * как текущий символ имени файла.
     *
     * Например:
     *
     * pattern:  "abc"
     * filename: "abc"
     *
     * Сравниваем:
     * 'a' == 'a'
     * 'b' == 'b'
     * 'c' == 'c'
     */
    if (*filename != '\0' && *pattern == *filename)
    {
        /*
         * Символы совпали.
         *
         * Проверяем оставшуюся часть шаблона
         * и оставшуюся часть имени файла.
         */
        return match(pattern + 1, filename + 1);
    }

    /*
     * Если символы не совпали,
     * имя файла не соответствует шаблону.
     */
    return 0;
}


/*
 * Главная функция программы.
 */
int main(void)
{
    /*
     * Массив для хранения шаблона.
     *
     * 1024 — максимальная длина введённого шаблона
     * вместе с завершающим '\0'.
     */
    char pattern[1024];

    /*
     * Выводим приглашение пользователю.
     */
    printf("Введите шаблон имени файла: ");

    /*
     * Считываем шаблон.
     *
     * fgets позволяет ограничить количество считываемых символов,
     * поэтому она безопаснее, чем gets.
     */
    if (fgets(pattern, sizeof(pattern), stdin) == NULL)
    {
        /*
         * Если ввод не удался,
         * завершаем программу с кодом ошибки.
         */
        return 1;
    }

    /*
     * fgets сохраняет символ '\n', если пользователь
     * нажал Enter и строка поместилась в массив.
     *
     * Нам этот символ не нужен, поэтому заменяем его
     * на завершающий символ строки '\0'.
     */
    pattern[strcspn(pattern, "\n")] = '\0';


    /*
     * По условию символ '/' не может встречаться
     * в шаблоне.
     *
     * Проверяем шаблон и при обнаружении '/'
     * выводим сообщение об ошибке.
     */
    if (strchr(pattern, '/') != NULL)
    {
        printf("Ошибка: символ '/' не может встречаться в шаблоне.\n");
        return 1;
    }


    /*
     * Открываем текущий каталог.
     *
     * "." означает текущий каталог.
     *
     * Функция opendir возвращает указатель DIR,
     * через который можно последовательно получать
     * записи каталога с помощью readdir.
     */
    DIR *dir = opendir(".");

    /*
     * Если каталог открыть не удалось,
     * сообщаем об ошибке.
     */
    if (dir == NULL)
    {
        perror("Не удалось открыть текущий каталог");
        return 1;
    }


    /*
     * Флаг found показывает,
     * был ли найден хотя бы один файл,
     * соответствующий шаблону.
     *
     * Изначально ничего не найдено,
     * поэтому устанавливаем 0.
     */
    int found = 0;


    /*
     * Структура dirent содержит информацию
     * об одной записи текущего каталога.
     *
     * Поле d_name содержит имя записи.
     */
    struct dirent *entry;


    /*
     * С помощью readdir последовательно получаем
     * все записи текущего каталога.
     *
     * Когда записи закончатся,
     * readdir вернёт NULL.
     */
    while ((entry = readdir(dir)) != NULL)
    {
        /*
        * Записи "." и ".." являются специальными записями каталога.
        * "." обозначает текущий каталог,
        * ".." обозначает родительский каталог.
        *
        * Это не обычные имена файлов, поэтому пропускаем их.
        */
        if (strcmp(entry->d_name, ".") == 0 ||
            strcmp(entry->d_name, "..") == 0)
        {
            continue;
        }

        /*
        * Проверяем оставшиеся имена на соответствие шаблону.
        */
        if (match(pattern, entry->d_name))
        {
            /*
            * Если имя подходит под шаблон,
            * выводим его на экран.
            */
            printf("%s\n", entry->d_name);

            /*
            * Запоминаем, что хотя бы одно совпадение найдено.
            */
            found = 1;
        }
    }


    /*
     * После окончания работы с каталогом
     * обязательно закрываем его.
     *
     * Это освобождает системные ресурсы.
     */
    closedir(dir);


    /*
     * Если ни одного подходящего имени найдено не было,
     * по условию задачи необходимо напечатать сам шаблон.
     */
    if (!found)
    {
        printf("%s\n", pattern);
    }


    /*
     * Программа завершилась успешно.
     */
    return 0;
}
